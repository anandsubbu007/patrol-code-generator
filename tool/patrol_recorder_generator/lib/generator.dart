String dartLiteral(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

String validateRelativePath(String value) {
  if (value.isEmpty ||
      value.length > 200 ||
      !RegExp(r'^[a-zA-Z0-9_./-]+$').hasMatch(value) ||
      value
          .split('/')
          .any((part) => part.isEmpty || part == '.' || part == '..')) {
    throw const FormatException(
      'Use a project-relative path without traversal or special characters.',
    );
  }
  return value;
}

class ExportConfig {
  ExportConfig({
    this.outputDirectory = 'patrol_test/recorded_journeys',
    this.journeyId = 'login',
    this.caseId = 'sign_in',
    this.caseName = 'Sign in with demonstration profile',
    this.profile = 'demo',
    this.recordingsDirectory = 'patrol_recorder',
    this.screenshotsDirectory = 'patrol_recorder/screenshots',
    this.appImport,
    this.appBuilder,
    this.waitTimeoutMs = 15000,
    this.maxScrolls = 60,
  }) {
    validateRelativePath(outputDirectory);
    validateRelativePath(recordingsDirectory);
    validateRelativePath(screenshotsDirectory);
    requireIdentifier(journeyId, 'Journey ID');
    requireIdentifier(caseId, 'Case ID');
    requireIdentifier(profile, 'Profile name');
    if (waitTimeoutMs < 100 ||
        waitTimeoutMs > 120000 ||
        maxScrolls < 1 ||
        maxScrolls > 200) {
      throw const FormatException(
        'wait_timeout_ms must be 100-120000; max_scrolls must be 1-200.',
      );
    }
    if (appImport != null || appBuilder != null) {
      RecorderAppConfig(
        appImport: appImport ?? 'package:app/main.dart',
        appBuilder: appBuilder ?? 'main',
      );
    }
    if (caseName.trim().isEmpty ||
        caseName.length > 120 ||
        caseName.codeUnits.any((c) => c < 32)) {
      throw const FormatException(
        'Case name must contain 1-120 printable characters.',
      );
    }
  }

  final String outputDirectory;
  final String journeyId;
  final String caseId;
  final String caseName;
  final String profile;
  final String recordingsDirectory;
  final String screenshotsDirectory;
  final String? appImport;
  final String? appBuilder;
  final int waitTimeoutMs;
  final int maxScrolls;
  String get yamlPath => '$recordingsDirectory/$journeyId.yml';
  String get directory => '$outputDirectory/$journeyId';
  String get testPath => '$directory/${journeyId}_test.dart';
  String get inputsPath => '$directory/${journeyId}_inputs.dart';
  String get contractPath => '$directory/${journeyId}_inputs.g.dart';
  String get stepsPath => '$directory/${journeyId}_steps.g.dart';
  String get tag => 'recorder_${journeyId}_$caseId';
  String get marker =>
      '// Generated by Patrol Recorder for $journeyId. Do not edit.\n';

  String command({bool singleCase = true, bool web = true}) =>
      'dart pub global run patrol_cli:main test --target $testPath'
      '${singleCase ? ' --tags $tag' : ''} --dart-define RECORDER_PROFILE=$profile'
      '${web ? ' --device chrome --web-headless' : ''}';

  factory ExportConfig.fromPubspec(String source, {String? expectedPackage}) {
    final document = loadYaml(source);
    if (document is! YamlMap || document['name'] is! String) {
      throw const FormatException(
        'The selected project needs a valid pubspec.yaml.',
      );
    }
    if (expectedPackage != null && document['name'] != expectedPackage) {
      throw FormatException(
        'Select the application project named $expectedPackage, not the recorder/tooling package.',
      );
    }
    final section = document['recorder_config'];
    if (section == null) return ExportConfig();
    if (section is! YamlMap) {
      throw const FormatException(
        'pubspec.yaml recorder_config must be a mapping.',
      );
    }
    const keys = {
      'output_directory',
      'journey_id',
      'case_id',
      'case_name',
      'profile',
      'recordings_directory',
      'screenshots_directory',
      'app_import',
      'app_builder',
      'wait_timeout_ms',
      'max_scrolls',
    };
    if (section.keys.any((key) => !keys.contains(key))) {
      throw const FormatException(
        'Unknown field in pubspec.yaml recorder_config.',
      );
    }
    String field(String key, String fallback) {
      if (!section.containsKey(key)) return fallback;
      final value = section[key];
      if (value is! String) {
        throw FormatException('recorder_config.$key must be a string.');
      }
      return value;
    }

    int number(String key, int fallback) {
      final value = section[key];
      if (!section.containsKey(key)) return fallback;
      if (value is! int) {
        throw FormatException('recorder_config.$key must be an integer.');
      }
      return value;
    }

    return ExportConfig(
      outputDirectory: field(
        'output_directory',
        'patrol_test/recorded_journeys',
      ),
      journeyId: field('journey_id', 'login'),
      caseId: field('case_id', 'sign_in'),
      caseName: field('case_name', 'Sign in with demonstration profile'),
      profile: field('profile', 'demo'),
      recordingsDirectory: field('recordings_directory', 'patrol_recorder'),
      screenshotsDirectory: field(
        'screenshots_directory',
        'patrol_recorder/screenshots',
      ),
      appImport: section.containsKey('app_import')
          ? field('app_import', '')
          : null,
      appBuilder: section.containsKey('app_builder')
          ? field('app_builder', '')
          : null,
      waitTimeoutMs: number('wait_timeout_ms', 15000),
      maxScrolls: number('max_scrolls', 60),
    );
  }
}

class InputRequirement {
  const InputRequirement(this.name, this.secret);
  final String name;
  final bool secret;
  String get getter =>
      'input${name.split('_').where((s) => s.isNotEmpty).map((s) => '${s[0].toUpperCase()}${s.substring(1)}').join()}';
  String get define => 'RECORDER_SECRET_${name.toUpperCase()}';
}

List<InputRequirement> requiredInputs(List<RecordedStep> steps) {
  final inputs = <String, bool>{};
  for (final step in steps.where((s) => s.input != null)) {
    final name = step.input!;
    if (inputs.containsKey(name) && inputs[name] != step.secret) {
      throw const FormatException(
        'An input cannot be both secret and non-secret.',
      );
    }
    inputs[name] = step.secret;
  }
  final result =
      inputs.entries.map((e) => InputRequirement(e.key, e.value)).toList()
        ..sort((a, b) => a.name.compareTo(b.name));
  if (result.map((r) => r.getter).toSet().length != result.length) {
    throw const FormatException(
      'Input names collide as Dart getters. Give those fields distinct stable keys.',
    );
  }
  return result;
}

class GeneratedJourney {
  const GeneratedJourney({
    required this.test,
    required this.data,
    required this.contract,
    required this.steps,
    required this.config,
    required this.needsImplementation,
  });
  final String test;

  /// User-owned implementation, never regenerated over an existing file.
  final String data;
  final String contract;
  final String steps;
  final ExportConfig config;
  final bool needsImplementation;

  Set<String> get userOwnedPaths => {config.testPath, config.inputsPath};
  Set<String> get generatedPaths => {config.contractPath, config.stepsPath};
  Map<String, Uint8List> files() => {
    for (final entry in {
      config.testPath: test,
      config.inputsPath: data,
      config.contractPath: contract,
      config.stepsPath: steps,
    }.entries)
      entry.key: Uint8List.fromList(utf8.encode(entry.value)),
  };
}

GeneratedJourney generateJourney({
  required List<RecordedStep> steps,
  required RecorderAppConfig app,
  required ExportConfig config,
  Map<String, String> inputValues = const {},
  Set<String> deferredInputs = const {},
}) {
  if (app.appImport == null || app.appBuilder == null) {
    throw const FormatException(
      'Resolve the app entrypoint before generating Dart.',
    );
  }
  if (steps.isEmpty) {
    throw const FormatException(
      'Include at least one supported action to generate a test.',
    );
  }
  for (final step in steps) {
    if (step.target.issue != null ||
        step.action == RecordedAction.unsupported) {
      throw FormatException(
        '${step.id}: ${step.target.issue ?? 'Action needs review'}. Resolve or explicitly exclude this step.',
      );
    }
  }
  final requirements = requiredInputs(steps);
  final names = requirements.map((r) => r.name).toSet();
  if (inputValues.keys.any((key) => !names.contains(key)) ||
      deferredInputs.any((key) => !names.contains(key))) {
    throw const FormatException('Input setup contains an unknown field.');
  }
  for (final r in requirements) {
    if (r.secret && inputValues.containsKey(r.name)) {
      throw const FormatException(
        'Secret values must be connected outside the generator.',
      );
    }
  }
  final profiles = <String, Map<String, String>>{
    for (final entry in app.safeProfiles.entries) entry.key: {...entry.value},
  };
  profiles[config.profile] = {...?profiles[config.profile], ...inputValues};
  for (final r in requirements.where(
    (r) => !r.secret && !deferredInputs.contains(r.name),
  )) {
    if ((profiles[config.profile]?[r.name] ?? '').trim().isEmpty) {
      throw FormatException(
        'Provide ${r.name}, or choose to connect it in the user-owned Dart input file.',
      );
    }
  }
  final formatter = DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  );
  final contract =
      config.marker +
      formatter.format('''
abstract class JourneyInputs {
  const JourneyInputs();
  ${requirements.map((r) => 'String get ${r.getter};').join('\n')}
}

void validateInputs(JourneyInputs inputs) {
  ${requirements.map((r) => '''
  if (inputs.${r.getter}.trim().isEmpty) {
    throw StateError(${dartLiteral('Missing ${r.secret ? 'secret' : 'input'}: ${r.name}. Connect ${r.getter} in ${config.journeyId}_inputs.dart.')});
  }''').join('\n')}
}
''');
  final getters = requirements
      .map((r) {
        String expression;
        if (deferredInputs.contains(r.name)) {
          expression =
              'throw StateError(${dartLiteral('Connect ${r.getter} in ${config.journeyId}_inputs.dart before running.')})';
        } else if (r.secret) {
          expression = 'const String.fromEnvironment(${dartLiteral(r.define)})';
        } else {
          expression =
              '''switch (profile) {
        ${profiles.entries.map((p) => '${dartLiteral(p.key)} => ${dartLiteral(p.value[r.name] ?? '')},').join('\n')}
        _ => throw StateError('Unknown RECORDER_PROFILE; inspect the user-owned inputs file.'),
      }''';
        }
        final guidance = deferredInputs.contains(r.name)
            ? '  // TODO: Connect ${r.getter} to your ${r.secret ? 'private test provider; never hardcode real secrets' : 'test fixture/provider'} before running.\n'
            : r.secret
            ? '  // TODO: Supply ${r.define} securely or connect ${r.getter} to your private test provider.\n'
            : '';
        return '$guidance@override\nString get ${r.getter} => $expression;';
      })
      .join('\n');
  final data = formatter.format('''
// User-owned. Connect fixtures or secret providers here. Regeneration preserves this file.
import '${config.journeyId}_inputs.g.dart';

/// User-owned input implementation; regeneration preserves this file.
///
/// Recorded values are not saved. Connect required inputs before replay.
/// Keep real credentials out of source code, YAML, and generated files.
class LocalJourneyInputs extends JourneyInputs {
  const LocalJourneyInputs(this.profile);
  final String profile;
  $getters
}

/// Loads test fixtures or private-provider data before replay.
///
/// Add asynchronous provider initialization here when needed.
Future<JourneyInputs> loadInputs() async {
  const profile = String.fromEnvironment('RECORDER_PROFILE', defaultValue: ${dartLiteral(config.profile)});
  if (!const <String>{${profiles.keys.map(dartLiteral).join(',')}}.contains(profile)) {
    throw StateError('Unknown RECORDER_PROFILE; inspect the user-owned inputs file.');
  }
  return const LocalJourneyInputs(profile);
}
''');
  String selector(RecorderSelector s) {
    final literal = dartLiteral(s.value);
    return switch (s.kind) {
      SelectorKind.key => 'find.byKey(const ValueKey<String>($literal))',
      SelectorKind.semanticsIdentifier =>
        'find.bySemanticsIdentifier($literal)',
      SelectorKind.semanticsLabel => 'find.bySemanticsLabel($literal)',
      SelectorKind.fieldLabel =>
        'find.byWidgetPredicate((widget) => widget is TextField && widget.decoration?.labelText == $literal)',
      SelectorKind.text => 'find.text($literal)',
      SelectorKind.richText => 'find.text($literal, findRichText: true)',
      SelectorKind.widgetType =>
        s.value == 'Scrollable'
            ? 'find.byElementPredicate((element) => element.widget is Scrollable && ModalRoute.of(element)?.isCurrent != false, description: "scrollable in the current route")'
            : 'find.byType(${s.value})',
    };
  }

  String finder(RecorderTarget target) => target.scope == null
      ? selector(target.selector!)
      : 'find.descendant(of: ${selector(target.scope!)}, matching: ${selector(target.selector!)})';
  final actions = steps.indexed
      .map((entry) {
        final (index, step) = entry;
        final name = 'target${index + 1}';
        final matches = 'matches${index + 1}';
        final timeout = 'const Duration(milliseconds: ${config.waitTimeoutMs})';
        final advice =
            '${step.id} (${step.action.name}) failed. Target: ${step.target.toJson()}. '
            'Add a unique ValueKey to this widget/scroll view or a keyed ancestor if ambiguous. '
            'For delayed UI, check the API fixture/loading state and recorder_config.wait_timeout_ms/max_scrolls. '
            'For a link, use unique text inside a keyed Text.rich or a keyed TextButton.';
        final action = switch (step.action) {
          RecordedAction.tap =>
            'await \$($name).tap(settlePolicy: SettlePolicy.noSettle, visibleTimeout: $timeout);',
          RecordedAction.longPress =>
            'await \$($name).longPress(settlePolicy: SettlePolicy.noSettle, visibleTimeout: $timeout);',
          RecordedAction.enterText =>
            'await \$.enterText($name, inputs.${requirements.singleWhere((r) => r.name == step.input).getter}, enablePatrolLog: false, settlePolicy: SettlePolicy.noSettle, visibleTimeout: $timeout);',
          RecordedAction.tapText =>
            '''
final link${index + 1} = find.textRange.ofSubstring(${dartLiteral(step.text!)}, descendentOf: $name);
expect(link${index + 1}.evaluate(), hasLength(1), reason: 'Link text must match exactly once inside the paragraph. Use unique text or a keyed WidgetSpan.');
await \$.tester.tapOnText(link${index + 1});
await \$.pump();
''',
          RecordedAction.scrollUntilVisible => '',
          RecordedAction.unsupported => throw const FormatException(
            'Unsupported action.',
          ),
        };
        final waiting = step.action == RecordedAction.scrollUntilVisible
            ? '''
final view${index + 1} = ${finder(step.scrollView!)};
await \$(view${index + 1}).waitUntilVisible(timeout: $timeout);
expect(view${index + 1}, findsOneWidget, reason: 'Scroll view is ambiguous. Add a unique ValueKey to the ScrollView.');
final scrollable${index + 1} = _recorderScrollables(view${index + 1});
expect(scrollable${index + 1}, findsOneWidget, reason: 'Cannot identify one primary Scrollable. Add a key to the intended ScrollView.');
final axis${index + 1} = \$.tester.widget<Scrollable>(scrollable${index + 1}).axisDirection;
expect(axis${index + 1} == AxisDirection.left || axis${index + 1} == AxisDirection.right,
  ${step.scrollDirection == RecordedScrollDirection.left || step.scrollDirection == RecordedScrollDirection.right},
  reason: 'The scroll axis changed. Re-record this layout.');
final distance${index + 1} = (\$.tester.getSize(view${index + 1}).${step.scrollDirection == RecordedScrollDirection.left || step.scrollDirection == RecordedScrollDirection.right ? 'width' : 'height'} * 0.6).clamp(20.0, 400.0).toDouble();
await \$.tester.scrollUntilVisible($name,
  axis${index + 1} == AxisDirection.${step.scrollDirection!.name} ? distance${index + 1} : -distance${index + 1},
  scrollable: scrollable${index + 1}, maxScrolls: ${config.maxScrolls},
  duration: const Duration(milliseconds: 250), continuous: true);
await \$($name).waitUntilVisible(timeout: $timeout);
'''
            : step.action == RecordedAction.tapText
            ? '''
await \$(find.descendant(of: $name,
  matching: find.textContaining(${dartLiteral(step.text!)}, findRichText: true),
  matchRoot: true)).waitUntilExists(timeout: $timeout);
'''
            : '''
await \$(find.descendant(of: $name, matching: find.byElementPredicate(_recorderEnabled),
  matchRoot: true)).waitUntilVisible(timeout: $timeout);
''';
        return '''
var $matches = 0;
try {
final $name = ${finder(step.target)};
$waiting
$matches = $name.evaluate().length;
expect($name, findsOneWidget, reason: ${dartLiteral('${step.id}: selector must match exactly one widget')});
$action
} catch (error, stack) {
  Error.throwWithStackTrace(StateError(${dartLiteral(advice)} ' Matching widgets: \$$matches. Failure type: \${error.runtimeType}.'), stack);
}
''';
      })
      .join('\n');
  final body = app.appBuilder == 'main'
      ? 'await Future<void>.sync(app.main).timeout(const Duration(milliseconds: ${config.waitTimeoutMs}), '
            "onTimeout: () => throw StateError('App main() timed out. Check startup futures/test services or recorder_config.wait_timeout_ms.'));\n"
            'await \$.pump();\n$actions'
      : 'await \$.tester.pumpWidget(app.${app.appBuilder}());\n$actions';
  final needsEnabled = steps.any(
    (s) =>
        s.action == RecordedAction.tap ||
        s.action == RecordedAction.longPress ||
        s.action == RecordedAction.enterText,
  );
  final needsScroll = steps.any(
    (s) => s.action == RecordedAction.scrollUntilVisible,
  );
  final selectors = [
    for (final step in steps) ...[
      step.target.selector!,
      if (step.target.scope != null) step.target.scope!,
    ],
  ];
  final needsMaterial =
      needsEnabled ||
      needsScroll ||
      selectors.any(
        (s) =>
            s.kind == SelectorKind.key ||
            s.kind == SelectorKind.widgetType ||
            s.kind == SelectorKind.fieldLabel,
      );
  final generatedSteps =
      config.marker +
      formatter.format('''
${needsEnabled ? "import 'dart:ui' as ui;" : ''}
${needsMaterial ? "import 'package:flutter/material.dart';" : ''}
import 'package:flutter_test/flutter_test.dart';
import 'package:patrol/patrol.dart';
import '${app.appImport}' as app;
import '${config.journeyId}_inputs.g.dart';

const recordedJourneyName = ${dartLiteral(config.caseName)};
const recordedJourneyTag = ${dartLiteral(config.tag)};

/// Replays recorded actions; callers must assert their expected business outcomes.
Future<void> runRecordedJourney(PatrolIntegrationTester \$, JourneyInputs inputs) async {
  validateInputs(inputs);
  final semantics = \$.tester.ensureSemantics();
  try { $body } finally { semantics.dispose(); }
}

${needsEnabled ? '''
bool _recorderEnabled(Element element) {
  var enabled = true;
  void inspect(Element e) {
    final w = e.widget;
    if (w is ButtonStyleButton && w.onPressed == null && w.onLongPress == null ||
        w is IconButton && w.onPressed == null ||
        w is Switch && w.onChanged == null ||
        w is Checkbox && w.onChanged == null ||
        w is TextField && (w.enabled == false || w.readOnly) ||
        w is EditableText && w.readOnly ||
        e.findRenderObject()?.debugSemantics?.getSemanticsData().flagsCollection.isEnabled == ui.Tristate.isFalse) {
      enabled = false;
    }
  }
  inspect(element);
  element.visitAncestorElements((e) { inspect(e); return enabled; });
  return enabled;
}
''' : ''}

${needsScroll ? '''
Finder _recorderScrollables(Finder view) {
  final root = view.evaluate().single;
  return find.byElementPredicate((element) {
    if (element.widget is! Scrollable) return false;
    if (root.widget is Scrollable) return identical(element, root);
    var inside = false;
    element.visitAncestorElements((parent) {
      if (identical(parent, root)) { inside = true; return false; }
      return parent.widget is! Scrollable;
    });
    return inside;
  }, description: 'primary Scrollable of the recorded view');
}
''' : ''}
''');
  final test = formatter.format('''
// User-owned. Add setup/assertions here. Regeneration preserves this file.
import 'package:patrol/patrol.dart';
import '${config.journeyId}_inputs.dart';
import '${config.journeyId}_steps.g.dart';

/// User-owned Patrol entrypoint; regeneration preserves setup and assertions.
///
/// Run from the application directory containing its Patrol dependency:
/// `patrol test --target ${config.testPath} --dart-define RECORDER_PROFILE=${config.profile}`
///
/// Use Patrol CLI, not the IDE's standard Run Test button or direct flutter test.
/// Patrol CLI generates test_bundle.dart and initializes patrolAppService.
/// Do not edit or commit test_bundle.dart.
void main() {
  patrolTest(recordedJourneyName, (\$) async {
    ${requirements.any((r) => deferredInputs.contains(r.name) || r.secret) ? '// TODO: Complete required getters in ${config.journeyId}_inputs.dart before running.' : ''}
    final inputs = await loadInputs().timeout(
      const Duration(milliseconds: ${config.waitTimeoutMs}),
      onTimeout: () => throw StateError('Input provider timed out. Check the fixture provider or increase recorder_config.wait_timeout_ms.'),
    );
    await runRecordedJourney(\$, inputs);
    // TODO: Add bounded waits and assertions for the expected final outcome.
  }, tags: [recordedJourneyTag]);
}
''');
  return GeneratedJourney(
    test: test,
    data: data,
    contract: contract,
    steps: generatedSteps,
    config: config,
    needsImplementation:
        deferredInputs.isNotEmpty || requirements.any((r) => r.secret),
  );
}
